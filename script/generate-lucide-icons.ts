const nodes = iconNodes as Record<string, unknown>
const output = `/**
 * Generated by yarn generate-icons from lucide-static (ISC).
 * See app/static/common/lucide-LICENSE for attribution. Do not edit by hand.
 * Legacy export names keep existing UI consumers source compatible.
 */
export type IconNode = readonly [
  'path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse',
  Readonly<Record<string, string>>
]
export type OcticonSymbolVariant = {
  readonly name: string
  readonly nodes: ReadonlyArray<IconNode>
  readonly w: number
  readonly h: number
  readonly brand?: boolean
  readonly filled?: boolean
}
export type OcticonSymbolVariants = Record<number, OcticonSymbolVariant>
export type OcticonSymbol = OcticonSymbolVariant | OcticonSymbolVariants

function symbol(name: string, nodes: ReadonlyArray<IconNode>, filled = false, brand = false): OcticonSymbolVariants {
  return {
    16: { name, nodes, w: 16, h: 16, filled, brand },
    24: { name, nodes, w: 24, h: 24, filled, brand },
  }
}

${Object.entries(mapping)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, lucide]) => {
    if (nodes[lucide] === undefined) {
      throw new Error(`Unknown Lucide icon: ${lucide}`)
    }
    const filled = name === 'dotFill' || name === 'squareFill'
    return `export const ${name} = symbol(${JSON.stringify(
      lucide
    )}, ${JSON.stringify(nodes[lucide])}, ${filled})`
  })
  .join('\n')}

// GitHub is a brand mark, not a generic UI icon. Retain its original artwork.
export const markGithub = symbol('github', ${JSON.stringify(
  githubMark.p.map(d => ['path', { d }])
)}, true, true)
`
async function writeIcons() {
  const root = Path.resolve(__dirname, '..')
  await fs.writeFile(
    Path.join(root, 'app/src/ui/octicons/octicons.generated.ts'),
    format(output, {
      parser: 'typescript',
      singleQuote: true,
      semi: false,
      trailingComma: 'es5',
    })
  )
  await fs.copyFile(
    Path.join(root, 'node_modules/lucide-static/LICENSE'),
    Path.join(root, 'app/static/common/lucide-LICENSE')
  )
  console.log(
    `Generated ${
      Object.keys(mapping).length
    } Lucide symbols and the GitHub brand mark`
  )
}

writeIcons().catch(error => {
  console.error(error)
  process.exitCode = 1
})
